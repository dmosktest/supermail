import type { MessageKey } from "./i18n-keys";
import { localeNames, type Locale } from "./site-config";

function pack(
  rows: Record<MessageKey, Partial<Record<Locale, string>> & { en: string }>,
): Record<Locale, Record<MessageKey, string>> {
  const keys = Object.keys(rows) as MessageKey[];
  const out = {} as Record<Locale, Record<MessageKey, string>>;
  for (const key of keys) {
    const byLocale = localeNames(rows[key]);
    for (const locale of Object.keys(byLocale) as Locale[]) {
      if (!out[locale]) out[locale] = {} as Record<MessageKey, string>;
      out[locale][key] = byLocale[locale];
    }
  }
  return out;
}

